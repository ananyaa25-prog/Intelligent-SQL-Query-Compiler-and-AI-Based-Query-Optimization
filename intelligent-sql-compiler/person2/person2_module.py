
from semantic_analyzer import validate_sql
from execution_engine import execute_sql
from evaluation import analyze_query, compare_queries


def process_query(original_sql, optimized_sql=None):
    """
    Main entry point for Person 2.

    original_sql:
        SQL generated by Person 1.

    optimized_sql:
        Optional rewritten SQL produced by Person 1.

    Returns a dictionary suitable for JSON serialization
    and frontend integration.
    """

    # 1. Validate the original SQL.
    original_validation = validate_sql(original_sql)

    if not original_validation["valid"]:
        return {
            "success": False,
            "stage": "original_semantic_validation",
            "error": original_validation["error"],
        }

    # 2. Choose the SQL that will actually execute.
    sql_to_execute = (
        optimized_sql
        if optimized_sql is not None
        else original_sql
    )

    # 3. Validate the SQL selected for execution.
    selected_validation = validate_sql(sql_to_execute)

    if not selected_validation["valid"]:
        return {
            "success": False,
            "stage": "selected_semantic_validation",
            "error": selected_validation["error"],
        }

    # 4. Execute only after validation.
    execution = execute_sql(sql_to_execute)

    if not execution["success"]:
        return {
            "success": False,
            "stage": "execution",
            "error": execution["error"],
        }

    # 5. Collect execution-plan information.
    plan = analyze_query(sql_to_execute)

    if not plan["success"]:
        return {
            "success": False,
            "stage": "plan_analysis",
            "error": plan["error"],
        }

    # 6. Compare original and optimized SQL if provided.
    comparison = None

    if optimized_sql is not None:
        comparison = compare_queries(
            original_sql,
            optimized_sql,
            repetitions=5,
        )

        if not comparison["success"]:
            return {
                "success": False,
                "stage": "optimization_evaluation",
                "error": comparison["error"],
                "execution": execution,
                "plan": plan,
            }

    return {
        "success": True,
        "original_sql": original_sql,
        "optimized_sql": optimized_sql,
        "executed_sql": sql_to_execute,
        "validation": {
            "original_valid": original_validation["valid"],
            "selected_valid": selected_validation["valid"],
        },
        "execution": execution,
        "plan": plan,
        "comparison": comparison,
    }


if __name__ == "__main__":
    original = """
    SELECT student_id, name
    FROM students
    WHERE gpa >= 9.0 AND gpa >= 8.0
    """

    optimized = """
    SELECT student_id, name
    FROM students
    WHERE gpa >= 9.0
    """

    result = process_query(original, optimized)

    if result["success"]:
        print("Integration successful!")
        print("Executed SQL:", result["executed_sql"])
        print("Columns:", result["execution"]["columns"])
        print("Rows:", result["execution"]["rows"][:5])
        print("Plan:", result["plan"]["plan"])
        print(
            "Results equivalent:",
            result["comparison"]["results_equivalent"],
        )
    else:
        print("Pipeline failed at:", result["stage"])
        print("Error:", result["error"])

